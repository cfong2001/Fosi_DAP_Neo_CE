"""Restore progress-band gaps and fill the two player surfaces in word bursts.

Homes are reserved from the unused tails of the contrast and pixel pockets.
The full fill is called only from the pinned full-screen player fill site;
unsupported display banks or rotation tail-call the original fill API.
"""
from pathlib import Path
import sys
import hashlib
from keystone import Ks, KS_ARCH_ARM, KS_MODE_THUMB
HERE=Path(__file__).resolve().parent
ROOT=HERE.parents[1]
sys.path[:0]=[str(ROOT/'tools'),str(ROOT/'patches/full/build')]
from rknano_image import Image
from build_tail import branch
GAPS,FULL,FULL_SITE=0x03052F40,0x03052D5C,0x0307EFB8


def payloads():
    ks=Ks(KS_ARCH_ARM,KS_MODE_THUMB)
    gap=bytes(ks.asm('''push {r4,r5,r6,lr};sub sp,#8;mov r6,r0;bl 0x305de30;str r6,[sp];adr r4,rects;movs r5,#5;
    again:ldrh r0,[r4];ldrh r1,[r4,#2];ldrh r2,[r4,#4];ldrh r3,[r4,#6];adds r4,#8;bl 0x30632fa;subs r5,#1;bne again;
    add sp,#8;pop {r4,r5,r6,pc};.balign 4,0;
    rects:.short 0,240,6,253,73,240,190,253,0,254,39,274,202,254,239,274,40,269,201,274
    ''',0x3052f40)[0]);assert len(gap)<=104
    full=bytes(ks.asm('''push {r4,r5,r6,lr};ldr r6,=0x30238b8;ldrh r4,[r6];cbnz r4,fallback;ldr r4,[r6,#20];cbnz r4,fallback;
    ldrh r4,[sp,#16];orr r4,r4,r4,lsl #16;bl 0x3063f10;
    mov r1,r4;mov r2,r4;mov r3,r4;ldr r0,=0x30065a8;movw r5,#7200;
    upper:stmia r0!,{r1,r2,r3,r4};subs r5,#1;bne upper;
    ldr r0,=0x306f224;movw r5,#2400;
    lower:stmia r0!,{r1,r2,r3,r4};subs r5,#1;bne lower;
    movs r0,#1;str r0,[r6,#12];movs r0,#0;strh r0,[r6,#32];strh r0,[r6,#34];pop {r4,r5,r6,pc};
    fallback:pop.w {r4,r5,r6,lr};b.w 0x30632fa;.ltorg
    ''',0x3052d5c)[0]);assert len(full)<=98
    return gap,full


def main():
    raw=(ROOT/'DP3_V137.img').read_bytes()
    assert hashlib.sha256(raw).hexdigest()=='fcc1cd3e35b46f1f8dbcb8da39fcc5eb3f1d469cdfade5e9c6ea3bd71ac6deef'
    image=Image(raw)
    gap,full=payloads()
    for number,label,module,address,code in (
        (276,'progress-gap-restore',0,GAPS,gap),
        (277,'player-full-fill',0,FULL,full),
        (278,'player-full-fill-hook',27,FULL_SITE,branch(FULL_SITE,FULL,True))):
        offset,size=image.module_region(module,'code');base=image.modules[module]['code_exec']
        assert base<=address and address+len(code)<=base+size
        expected=raw[offset+address-base:offset+address-base+len(code)]
        name=f'{number:04d}-{label}'
        (HERE/(name+'.patch')).write_text(
            '# Generated by build_player_repaint.py.\n'+f'name: {name}\nkind: module\nmodule: {module}\nregion: code\naddress: {address:#x}\n'
            +f'expect: {expected.hex()}\nreplace: {code.hex()}\n'
            +'gate: stock bytes; native progress-band coverage, framebuffer/context/ABI parity and instruction counts\n'
            +'rationale: Restore the background gaps around the progress bar without erasing time labels, then preserve the existing bar repaint. The dedicated full-player fill writes eight pixels per burst across both physical spans and falls back on unsupported bank or rotation. No persistent RAM is added.\n')
    # Keep the C builder's ordinary entry patch, including its stock-byte
    # extent, synchronized with the absolute Thumb call in artwork.c.
    from keystone import Ks, KS_ARCH_ARM, KS_MODE_THUMB
    ks=Ks(KS_ARCH_ARM,KS_MODE_THUMB)
    entry=bytes(ks.asm('push {r0-r4,lr};ldr r0,=0x03004400;ldrh r0,[r0];ldr ip,=0x03052F41;blx ip;pop.w {r0-r4,lr};ldr ip,=0x030632FB;bx ip;.hword 0;.ltorg',0x03053EF4)[0])
    assert len(entry)<=0x03053F42-0x03053EF4
    offset,_=image.module_region(0,'code');base=image.modules[0]['code_exec']
    expected=raw[offset+0x03053EF4-base:offset+0x03053EF4-base+len(entry)]
    path=HERE/'0183-artwork-bar_entry.patch';lines=path.read_text().splitlines()
    lines=[('replace: '+entry.hex()) if line.startswith('replace: ') else
           ('expect: '+expected.hex()) if line.startswith('expect: ') else line for line in lines]
    path.write_text('\n'.join(lines)+'\n')
    print(f'Progress gaps: {len(gap)} bytes; full fill: {len(full)} bytes')


if __name__=='__main__':main()
