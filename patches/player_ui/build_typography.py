#!/usr/bin/env python3
"""Build bounded in-place time text, marquee timing and English labels."""
import json
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
sys.path.insert(0, str(REPO / 'tools'))
from rknano_image import Image
sys.path.insert(0, str(REPO / 'patches/theater/build'))
from build_theater import branch


def main():
    raw = (REPO / 'DP3_V137.img').read_bytes()
    im = Image(raw)
    assert __import__('hashlib').sha256(raw).hexdigest() == 'fcc1cd3e35b46f1f8dbcb8da39fcc5eb3f1d469cdfade5e9c6ea3bd71ac6deef'
    def patch(name, mod, address, code, rationale):
        off, length = im.module_region(mod, 'code')
        pos = address - im.modules[mod]['code_exec']
        assert 0 <= pos and pos + len(code) <= length
        expect = raw[off+pos:off+pos+len(code)]
        (HERE / (name+'.patch')).write_text(
            f'# Generated by build_typography.py.\nname: {name}\nkind: module\n'
            f'module: {mod}\nregion: code\naddress: {address:#x}\n'
            'gate: pinned stock bytes; Unicorn typography regression suite\n'
            f'expect: {expect.hex()}\nreplace: {code.hex()}\nrationale: {rationale}\n')
    with tempfile.TemporaryDirectory() as tmp:
        b = Path(tmp)
        (b/'link.ld').write_text('SECTIONS { .time 0x0307E72C : { *(.text.time) } .marquee 0x03053114 : { *(.text.marquee) } /DISCARD/ : { *(.ARM*) *(.comment) } }')
        subprocess.run(['arm-none-eabi-gcc','-mcpu=cortex-m3','-mthumb','-nostdlib','-Wl,-T,'+str(b/'link.ld'),str(HERE/'typography.S'),'-o',str(b/'ui.elf')],check=True)
        for section, mod, address, limit, name in (
            ('time',27,0x0307E72C,148,'0150-player-time-font'),
            ('marquee',0,0x03053114,20,'0151-marquee-stamp')):
            subprocess.run(['arm-none-eabi-objcopy','-O','binary','--only-section=.'+section,str(b/'ui.elf'),str(b/'part.bin')],check=True)
            code=(b/'part.bin').read_bytes(); assert len(code)<=limit,(section,len(code),limit)
            patch(name,mod,address,code,'Main-font time text in the existing time routine.' if mod else 'Reset the marquee interval to 50 ticks after its first draw. The 20-byte tier-1 pocket has no static references (patches/space/census.json).')
    patch('0152-marquee-dwell',0,0x030630BA,bytes.fromhex('96218185'),'Register a 150-tick initial pause in the existing interval field; no new state.')
    patch('0153-marquee-step-stamp',0,0x0306300E,branch(0x0306300E,0x03053114,True),'After a successful scroll draw, stamp the current tick and use 50 ticks between subsequent steps.')
    patch('0154-play-all-albums',23,0x0307DA44,('Play All Albums'+'\0').encode('utf-16le'),'Correct the inline English album action in its existing 32-byte slot.')
    labels={82:'Artists',83:'Albums'}
    # The album-list first entry has its own label, distinct from the category.
    english=list(im.lang(2))
    for row in english:
        if row['text'].lower() in ('play all','play all album','play all albums','all album'):
            labels[row['id']]='Play All Albums'
    runs=[]
    for sid,text in labels.items():
        row=english[sid];off=row['file_offset'];code=(text+'\0').encode('utf-16le')
        runs.append({'offset':off,'expect':raw[off:off+len(code)].hex(),'replace':code.hex()})
    (HERE/'labels.json').write_text(json.dumps({'version':1,'runs':runs},indent=1)+'\n')
    print('labels',labels)

if __name__=='__main__':main()
