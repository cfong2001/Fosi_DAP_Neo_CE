#!/usr/bin/env python3
"""Place original metadata code around the player's shared literal pool."""
import hashlib
import subprocess
import sys
import tempfile
from pathlib import Path
HERE=Path(__file__).resolve().parent
REPO=HERE.parents[1]
sys.path.insert(0,str(REPO/'tools'))
from rknano_image import Image
sys.path.insert(0,str(REPO/'patches/theater/build'))
from build_theater import branch

def main():
    raw=(REPO/'DP3_V137.img').read_bytes()
    assert hashlib.sha256(raw).hexdigest()=='fcc1cd3e35b46f1f8dbcb8da39fcc5eb3f1d469cdfade5e9c6ea3bd71ac6deef'
    im=Image(raw);off,n=im.module_region(27,'code');base=im.modules[27]['code_exec']
    def patch(name,address,code):
        p=address-base;assert 0<=p and p+len(code)<=n
        (HERE/(name+'.patch')).write_text(
            '# Generated by build_metadata.py.\n'+f'name: {name}\nkind: module\nmodule: 27\nregion: code\naddress: {address:#x}\n'
            'gate: pinned stock bytes; metadata painter Unicorn regressions\n'+
            f'expect: {raw[off+p:off+p+len(code)].hex()}\nreplace: {code.hex()}\n'
            'rationale: Replace the old metadata painter in place and preserve its shared literal pool at 0x0307ECA4..0x0307ED60.\n')
    with tempfile.TemporaryDirectory() as tmp:
        b=Path(tmp)
        (b/'link.ld').write_text('''SECTIONS {
 .info 0x0307E988 : { *(.text.info) }
 .helper 0x0307ED60 : { *(.text.helper) *(.text.title) *(.rodata*) }
 /DISCARD/ : { *(.ARM*) *(.comment) }
 }''')
        subprocess.run(['arm-none-eabi-gcc','-mcpu=cortex-m3','-mthumb','-std=c99','-Os','-ffreestanding','-fno-builtin','-nostdlib','-Wall','-Wextra','-Werror','-Wl,-T,'+str(b/'link.ld'),str(HERE/'metadata.c'),'-o',str(b/'m.elf')],check=True)
        syms={line.split()[2]:int(line.split()[0],16) for line in subprocess.check_output(['arm-none-eabi-nm','-n',str(b/'m.elf')],text=True).splitlines() if len(line.split())==3}
        for part,addr,limit,name in [('info',0x0307E988,0x0307EBA8,'0160-track-info'),('helper',0x0307ED60,0x0307EEB0,'0161-metadata-helpers')]:
            dest=b/(part+'.bin')
            subprocess.run(['arm-none-eabi-objcopy','-O','binary','--only-section=.'+part,str(b/'m.elf'),str(dest)],check=True)
            code=dest.read_bytes();assert addr+len(code)<=limit,(part,len(code),limit-addr)
            patch(name,addr,code);print(part,len(code),'bytes')
        # Two-byte bridge skips the alignment halfword; old entry remains callable.
        patch('0162-track-info-entry',0x0307E986,bytes.fromhex('ffe7'))
        code=bytes.fromhex('4348') # Original literal at 0x0307FADC: destination buffer.
        code+=branch(0x0307F9CE,syms['player_title'],True)
        code+=branch(0x0307F9D2,0x0307F9EE)
        patch('0163-player-tag-title',0x0307F9CC,code)

if __name__=='__main__':main()
