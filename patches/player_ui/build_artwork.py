#!/usr/bin/env python3
"""Build bounded artwork compositors in existing code pockets and UI slots."""
import hashlib
import json
import struct
import subprocess
import sys
import tempfile
from pathlib import Path
HERE=Path(__file__).resolve().parent
REPO=HERE.parents[1]
sys.path.insert(0,str(REPO/'tools'))
from rknano_image import Image
sys.path.insert(0,str(REPO/'patches/theater/build'))
from build_theater import branch

# Resident routines use census pockets; UI-only draws fit the old info painter.
PARTS=(('row',0,0x0306D13C,0x0306D23C,170),
       ('contrast',0,0x03052D04,0x03052DBE,171),
       ('round',0,0x03054308,0x03054342,172),
       ('pixels',0,0x03052EE4,0x03052FA8,173),
       ('placeholder',27,0x0307EBA8,0x0307ECA4,174),
       ('badge',0,0x03056160,0x0305622C,175),
       ('formats',27,0x0307EEB0,0x0307EF4E,177),
       ('badge_fill',0,0x03053908,0x03053966,178))

def main():
    raw=(REPO/'DP3_V137.img').read_bytes()
    assert hashlib.sha256(raw).hexdigest()=='fcc1cd3e35b46f1f8dbcb8da39fcc5eb3f1d469cdfade5e9c6ea3bd71ac6deef'
    im=Image(raw)
    def patch(name,mod,address,code):
        off,n=im.module_region(mod,'code');pos=address-im.modules[mod]['code_exec']
        assert 0<=pos and pos+len(code)<=n
        (HERE/(name+'.patch')).write_text('# Generated by build_artwork.py.\n'+
            f'name: {name}\nkind: module\nmodule: {mod}\nregion: code\naddress: {address:#x}\n'
            'gate: pinned stock bytes; artwork compositor Unicorn regression suite\n'+
            f'expect: {raw[off+pos:off+pos+len(code)].hex()}\nreplace: {code.hex()}\n'
            'rationale: Original row compositor or player-only drawing in audited stock code slots, with no new persistent RAM.\n')
    with tempfile.TemporaryDirectory() as tmp:
        b=Path(tmp)
        sections='\n'.join(f'.{p} {a:#x} : {{ *(.text.{p})'+(' *(.rodata) *(.rodata.edge*)' if p=='round' else ' *(.rodata.formats)' if p=='formats' else '')+' }' for p,m,a,e,n in PARTS)
        (b/'link.ld').write_text('SECTIONS {\n'+sections+'\n/DISCARD/ : { *(.ARM*) *(.comment) } }')
        subprocess.run(['arm-none-eabi-gcc','-mcpu=cortex-m3','-mthumb','-std=c99','-Os','-ffreestanding','-fno-builtin','-nostdlib','-Wall','-Wextra','-Werror','-Wl,-T,'+str(b/'link.ld'),str(HERE/'artwork.c'),'-o',str(b/'art.elf')],check=True)
        for part,mod,addr,end,number in PARTS:
            dest=b/(part+'.bin')
            subprocess.run(['arm-none-eabi-objcopy','-O','binary','--only-section=.'+part,str(b/'art.elf'),str(dest)],check=True)
            code=dest.read_bytes();assert addr+len(code)<=end,(part,len(code),end-addr)
            patch(f'{number:04}-artwork-{part}',mod,addr,code)
            print(part,len(code),'bytes')
    patch('0176-artwork-centered-box',27,0x0307E8D2,bytes.fromhex('3020'))

    # Remove the record from the player ground in both themes. The placeholder
    # is drawn only by the player's no-art exit, not baked behind real covers.
    runs=[]
    def changes(off,old,new):
        start=None
        for i in range(0,len(new),2):
            if new[i:i+2]!=old[i:i+2]:
                if start is None:start=i
            elif start is not None:
                runs.append({'offset':off+start,'expect':old[start:i].hex(),'replace':new[start:i].hex()});start=None
        if start is not None:runs.append({'offset':off+start,'expect':old[start:].hex(),'replace':new[start:].hex()})
    entries={e['id']:e for e in im.images()}
    for rid in (138,304):
        e=entries[rid];off=e['data_offset'];size=e['size'];old=raw[off:off+size];new=bytearray(old)
        ground=old[:2]
        for y in range(25,192):new[y*480:(y+1)*480]=ground*240
        changes(off,old,new)
    (HERE/'artwork-resources.json').write_text(json.dumps({'version':1,'runs':runs},indent=1)+'\n')
    print('artwork resource runs',len(runs))
if __name__=='__main__':main()
