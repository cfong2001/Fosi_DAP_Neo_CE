"""Adapt native Ogg artwork loading to OpusTags and segment-table continuation."""
from pathlib import Path
import sys
from keystone import Ks, KS_ARCH_ARM, KS_MODE_THUMB
HERE=Path(__file__).resolve().parent
ROOT=HERE.parents[1]
sys.path[:0]=[str(ROOT/'tools'),str(ROOT/'patches/full/build')]
from rknano_image import Image
from build_tail import branch

def edits():
    result=[]
    def put(mod,addr,data):result.append((mod,addr,data))
    home=0x306d734
    ks=Ks(KS_ARCH_ARM,KS_MODE_THUMB)
    code=bytes(ks.asm('''
     ldrb.w r0,[sp,#0x11c];cmp r0,#79;bne vorbis;
     mov r2,r7;movs r1,#1;addw r0,sp,#0x116;bl 0x3058fa8;
     cmp r0,#1;bne fail;
      movs r2,#7;ldr r1,=0x308334a;addw r0,sp,#0x110;bl 0x3054ed8;
     cbz r0,opus;b.w 0x3083352;
     opus:b.w 0x3083846;
     vorbis:cmp r0,#3;beq native;b.w 0x308381e;
     native:b.w 0x3083812;
     fail:b.w 0x308389a;
     .ltorg
    ''',home)[0]);assert len(code)<=74
    put(0,home,code);put(18,0x3083346,branch(0x3083346,0x3083750));put(18,0x308334a,b'pusTags\0');put(18,0x308380a,branch(0x308380a,home)+b'\x00\xbf'*2)
    put(18,0x3083352,bytes(ks.asm('mov r2,r7;movs r1,#1;mov.w r0,#-1;bl 0x30594a0;b.w 0x308381e',0x3083352)[0]))
    arg=bytes(ks.asm('''
     ldrb.w r2,[sp,#0x11c];cmp r2,#79;bne vorbis;
     cmp r1,#8;blo bad;sub r2,r1,#8;ldrb.w r3,[sp,#0x108];cbz r3,bad;add r3,r5;ldrb r3,[r3,#-1];
     cmp r3,#255;ite eq;moveq.w r3,#-1;movne r3,#0;b.w 0x308386a;
     vorbis:sub r2,r1,#7;mov r3,r4;b.w 0x308386a;
     bad:b.w 0x308389a
    ''',0x306d7f8)[0]);assert len(arg)<=68
    put(0,0x306d7f8,arg);put(18,0x3083866,branch(0x3083866,0x306d7f8))
    cont=bytes(ks.asm('''
     ldrb.w r1,[sp,#0x748];cbz r1,fail;
     addw r0,sp,#0x600;add r0,r1;ldrb r0,[r0,#-1];cmp r0,#255;
     ite eq;moveq.w r0,#-1;movne r0,#0;str.w r0,[sp,#0x744];b.w 0x3083172;
     fail:b.w 0x3082e4e
    ''',0x3061252)[0]);assert len(cont)<=46
    put(0,0x3061252,cont);put(18,0x308316e,branch(0x308316e,0x3061252))
    return result


def main():
    stock=(ROOT/'DP3_V137.img').read_bytes();im=Image(stock)
    names=[]
    for number,(mod,address,code) in enumerate(edits(),266):
        offset,size=im.module_region(mod,'code');base=im.modules[mod]['code_exec']
        assert base<=address and address+len(code)<=base+size
        expected=stock[offset+address-base:offset+address-base+len(code)]
        name=f'{number:04d}-opus-artwork'
        (HERE/(name+'.patch')).write_text(
            '# Generated by build_artwork_route.py.\n'+f'name: {name}\nkind: module\nmodule: {mod}\nregion: code\naddress: {address:#x}\n'
            +f'expect: {expected.hex()}\nreplace: {code.hex()}\n'
            +'gate: stock bytes; native extraction, JPEG rows, theater reference and Vorbis control\n'
            +'rationale: Replace obsolete ASF artwork admission with Opus Ogg handling; consume the eight-byte OpusTags signature and follow lacing rather than granule positions across comment pages. Native base64, temporary-file and JPEG paths remain in use.\n')
        names.append('../opus_swap/'+name+'.patch')
    print('\n'.join(names))

if __name__=='__main__':main()
