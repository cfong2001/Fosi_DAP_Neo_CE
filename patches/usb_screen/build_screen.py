#!/usr/bin/env python3
"""Build the USB audio transport card and remove the redundant connection label."""
import hashlib, subprocess, sys, tempfile
from pathlib import Path
HERE=Path(__file__).resolve().parent
REPO=HERE.parents[1]
sys.path[:0]=[str(REPO/'tools'),str(REPO/'patches/theater/build')]
from rknano_image import Image
from build_theater import branch
PARTS=(('usb_card',0x0306004C,0x030600AE,190),('usb_lines',0x03054404,0x030544A8,191))
def main():
    raw=(REPO/'DP3_V137.img').read_bytes()
    assert hashlib.sha256(raw).hexdigest()=='fcc1cd3e35b46f1f8dbcb8da39fcc5eb3f1d469cdfade5e9c6ea3bd71ac6deef'
    im=Image(raw)
    def patch(name,mod,addr,code):
        off,n=im.module_region(mod,'code');p=addr-im.modules[mod]['code_exec'];assert 0<=p and p+len(code)<=n
        (HERE/(name+'.patch')).write_text('# Generated by build_screen.py.\n'+f'name: {name}\nkind: module\nmodule: {mod}\nregion: code\naddress: {addr:#x}\ngate: pinned stock bytes; USB screen emulation\nexpect: {raw[off+p:off+p+len(code)].hex()}\nreplace: {code.hex()}\nrationale: Display the actual fixed UAC transport format without claiming host file metadata; preserve USB protocol and window state.\n')
    with tempfile.TemporaryDirectory() as tmp:
        b=Path(tmp)
        (b/'link.ld').write_text('SECTIONS { .usb_card 0x0306004C : { *(.text.usb_card) } .usb_lines 0x03054404 : { *(.rodata.usb_lines) } /DISCARD/ : { *(.ARM*) *(.comment) } }')
        subprocess.run(['arm-none-eabi-gcc','-mcpu=cortex-m3','-mthumb','-std=c11','-Os','-ffreestanding','-fno-builtin','-nostdlib','-Wall','-Wextra','-Werror','-Wl,-T,'+str(b/'link.ld'),str(HERE/'screen.c'),'-o',str(b/'screen.elf')],check=True)
        for part,addr,end,num in PARTS:
            dest=b/(part+'.bin');subprocess.run(['arm-none-eabi-objcopy','-O','binary','--only-section=.'+part,str(b/'screen.elf'),str(dest)],check=True)
            data=dest.read_bytes();assert addr+len(data)<=end,(part,len(data));patch(f'{num:04}-{part.replace("_","-")}',0,addr,data);print(part,len(data))
    patch('0192-usb-audio-card-hook',9,0x0308072C,branch(0x0308072C,0x0306004C,True))
    patch('0193-usb-connected-hide',9,0x030807A8,bytes.fromhex('00bf00bf'))
if __name__=='__main__':main()
