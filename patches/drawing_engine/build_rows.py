#!/usr/bin/env python3
"""Build row blitters in explicitly allocated, censused resident code pockets."""
import hashlib,json,struct,subprocess,sys,tempfile
from pathlib import Path
HERE=Path(__file__).resolve().parent
REPO=HERE.parents[1]
sys.path[:0]=[str(REPO/'tools'),str(REPO/'patches/theater/build')]
from rknano_image import Image
from build_theater import branch
PARTS=(
 ('eligible',0x030611EC,0x0306123A),('row_at',0x03052698,0x030526C8),
 ('finish_rect',0x03052314,0x0305234C),('fast_fill',0x0305557C,0x030555D2),
 ('opaque_rows',0x0305A9B8,0x0305AA18),('finish_sparse',0x03061478,0x030614D4),
 ('mono_rows',0x0306100C,0x03061070),('fast_bitmap',0x03052A18,0x03052A84),
 ('keyed_rows',0x03063FCC,0x030640A6),('fast_keyed',0x03059594,0x030595CE),
 ('fast_flash',0x0306CE00,0x0306CEB2),('fast_clear',0x0305E824,0x0305E860),
 ('wrap_fill',0x0305043C,0x03050480),('wrap_fg',0x03050B10,0x03050B52),
 ('wrap_bitmap',0x03051424,0x0305146A),('wrap_keyed',0x03051480,0x030514CC),
 ('wrap_flash',0x03052244,0x03052290),('wrap_clear',0x03050BD4,0x03050C16),
 ('mono_line',0x03052E04,0x03052E8A),('finish_keyed',0x03065690,0x030656EE))
HOOKS=(('fill',0x030632FA,4,'fast_fill',1),('fg',0x030632B4,4,'fast_fill',0),
       ('bitmap',0x0306333E,4,'fast_bitmap',2),('keyed',0x0306373C,4,'fast_keyed',3),
       ('flash',0x03063444,8,'fast_flash',1),('clear',0x03063F92,4,'fast_clear',0))
def main():
    raw=(REPO/'DP3_V137.img').read_bytes();assert hashlib.sha256(raw).hexdigest()=='fcc1cd3e35b46f1f8dbcb8da39fcc5eb3f1d469cdfade5e9c6ea3bd71ac6deef'
    im=Image(raw);off,n=im.module_region(0,'code');base=im.modules[0]['code_exec']
    def patch(name,addr,code):
        p=addr-base;assert 0<=p and p+len(code)<=n
        (HERE/(name+'.patch')).write_text('# Generated by build_rows.py.\n'+f'name: {name}\nkind: module\nmodule: 0\nregion: code\naddress: {addr:#x}\ngate: pinned stock bytes; stock-versus-fast framebuffer and fallback emulation\nexpect: {raw[off+p:off+p+len(code)].hex()}\nreplace: {code.hex()}\nrationale: Original row drawing code in an allocated unreachable stock routine; preserve original entry instructions and resume stock on unsupported geometry or mode.\n')
    with tempfile.TemporaryDirectory() as tmp:
        b=Path(tmp);asm=['.syntax unified','.thumb','.cpu cortex-m3']
        for name,site,count,target,args in HOOKS:
            asm += [f'.section .text.wrap_{name},"ax",%progbits',f'.global wrap_{name}', '.thumb_func',f'wrap_{name}:','push {r0-r4,lr}','sub sp,#16']
            for i in range(args):asm += [f'ldr r4,[sp,#{40+4*i}]',f'str r4,[sp,#{4*i}]']
            if name=='fg':asm += ['ldr r4,=0x0302385C','ldrh r4,[r4]','str r4,[sp]']
            asm += [f'bl {target}','add sp,#16','cmp r0,#0','pop {r0-r4,lr}',f'beq fallback_{name}','bx lr',f'fallback_{name}:']
            prefix=raw[off+site-base:off+site-base+count]
            asm += ['.hword '+','.join(hex(v) for v in struct.unpack('<'+'H'*(count//2),prefix)),f'b.w resume_{name}',f'.thumb_set resume_{name}, {site+count+1:#x}', '.ltorg']
        (b/'wrappers.S').write_text('\n'.join(asm)+'\n')
        sections='\n'.join(f'.{part} {addr:#x} : {{ *(.text.{part}) }}' for part,addr,end in PARTS)
        (b/'link.ld').write_text('SECTIONS {\n'+sections+'\n/DISCARD/ : { *(.ARM*) *(.comment) } }')
        subprocess.run(['arm-none-eabi-gcc','-mcpu=cortex-m3','-mthumb','-std=c99','-Os','-ffreestanding','-fno-builtin','-ffunction-sections','-fdata-sections','-nostdlib','-Wall','-Wextra','-Werror','-Wl,-T,'+str(b/'link.ld'),str(HERE/'rows.c'),str(b/'wrappers.S'),'-o',str(b/'rows.elf')],check=True)
        for num,(part,addr,end) in enumerate(PARTS,200):
            dest=b/(part+'.bin');subprocess.run(['arm-none-eabi-objcopy','-O','binary','--only-section=.'+part,str(b/'rows.elf'),str(dest)],check=True)
            data=dest.read_bytes();assert addr+len(data)<=end,(part,len(data),end-addr)
            patch(f'{num:04}-rows-{part.replace("_","-")}',addr,data);print(part,len(data))
        addresses={part:addr for part,addr,end in PARTS}
        for num,(name,site,count,target,args) in enumerate(HOOKS,220):
            patch(f'{num:04}-rows-hook-{name}',site,branch(site,addresses['wrap_'+name])+b'\x00\xbf'*((count-4)//2))
if __name__=='__main__':main()
