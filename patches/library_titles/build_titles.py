#!/usr/bin/env python3
"""Keep parsed title tags in the library database; fall back only when empty."""
import hashlib
import sys
from pathlib import Path
HERE=Path(__file__).resolve().parent
REPO=HERE.parents[1]
sys.path.insert(0,str(REPO/'tools'))
from rknano_image import Image
sys.path.insert(0,str(REPO/'patches/theater/build'))
from build_theater import branch
from keystone import Ks,KS_ARCH_ARM,KS_MODE_THUMB

def main():
    raw=(REPO/'DP3_V137.img').read_bytes()
    assert hashlib.sha256(raw).hexdigest()=='fcc1cd3e35b46f1f8dbcb8da39fcc5eb3f1d469cdfade5e9c6ea3bd71ac6deef'
    im=Image(raw)
    def patch(name,mod,addr,code):
        off,n=im.module_region(mod,'code');p=addr-im.modules[mod]['code_exec']
        assert 0<=p and p+len(code)<=n
        (HERE/(name+'.patch')).write_text('# Generated by build_titles.py.\n'+f'name: {name}\nkind: module\nmodule: {mod}\nregion: code\naddress: {addr:#x}\n'
            'gate: pinned stock bytes; library scanner title-copy Unicorn regression\n'+f'expect: {raw[off+p:off+p+len(code)].hex()}\nreplace: {code.hex()}\n'
            'rationale: Keep the parsed title already stored in the scan record; copy the filename only for an empty title. No browse-time file opens or tag parsing.\n')
    base=0x0305318C
    # r0=title destination, r1=filename source, r2=256 bytes. All are the
    # scanner's original memcpy arguments; its caller reloads volatile regs.
    ks=Ks(KS_ARCH_ARM,KS_MODE_THUMB)
    code=bytes(ks.asm('ldrh r3,[r0]; cbnz r3,done; b.w 0x03054e34; done: bx lr',base)[0])
    assert len(code)<=20
    patch('0180-library-title-fallback',0,base,code)
    patch('0181-library-title-copy-hook',38,0x0307EF5C,branch(0x0307EF5C,base,True))
    print('library title fallback',len(code),'bytes')
if __name__=='__main__':main()
